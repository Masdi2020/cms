-- ============================================================
-- 13. HELPER: CEK ADMIN
-- ============================================================

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.users
        where id = auth.uid()
          and role = 'admin'::public.user_role
    );
$$;

-- ============================================================
-- 14. HELPER: CEK KETUA PANITIA EVENT
-- ============================================================

create or replace function public.is_event_chair(p_event_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.events e
        where e.id = p_event_id
          and e.ketua_panitia_id = auth.uid()
    );
$$;

-- ============================================================
-- 15. HELPER: CEK ANGGOTA EVENT
-- ============================================================

create or replace function public.is_event_member(p_event_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.members m
        join public.divisions d on d.id = m.division_id
        where m.user_id = auth.uid()
          and d.event_id = p_event_id
    );
$$;

-- ============================================================
-- 16. HELPER: CEK AKSES EVENT
-- ============================================================

create or replace function public.can_access_event(p_event_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select
        public.is_admin()
        or public.is_event_chair(p_event_id)
        or public.is_event_member(p_event_id);
$$;

-- ============================================================
-- 17. HELPER: CEK HAK KELOLA DIVISI
-- ============================================================

create or replace function public.can_manage_division(p_division_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.divisions d
        where d.id = p_division_id
          and (
              public.is_admin()
              or public.is_event_chair(d.event_id)
          )
    );
$$;

-- ============================================================
-- 18. HELPER: CEK AKSES TASK
-- ============================================================

create or replace function public.can_access_task(p_task_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.tasks t
        join public.divisions d on d.id = t.division_id
        where t.id = p_task_id
          and public.can_access_event(d.event_id)
    );
$$;

-- ============================================================
-- 19. RLS POLICY: EVENTS
-- ============================================================

create policy "users can view related events"
on public.events
for select
to authenticated
using (public.can_access_event(id));

create policy "admin can create events"
on public.events
for insert
to authenticated
with check (public.is_admin());

create policy "admin or chair can update event"
on public.events
for update
to authenticated
using (
    public.is_admin()
    or public.is_event_chair(id)
);

create policy "admin can delete event"
on public.events
for delete
to authenticated
using (public.is_admin());

-- ============================================================
-- 20. RLS POLICY: DIVISIONS
-- ============================================================

create policy "users can view divisions"
on public.divisions
for select
to authenticated
using (public.can_access_event(event_id));

create policy "admin or chair can create divisions"
on public.divisions
for insert
to authenticated
with check (
    public.is_admin()
    or public.is_event_chair(event_id)
);

create policy "admin or chair can update divisions"
on public.divisions
for update
to authenticated
using (
    public.is_admin()
    or public.is_event_chair(event_id)
)
with check (
    public.is_admin()
    or public.is_event_chair(event_id)
);

create policy "coordinator can update own division name"
on public.divisions
for update
to authenticated
using (coordinator_id = auth.uid())
with check (coordinator_id = auth.uid());

create or replace function public.guard_division_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not public.is_admin() and not public.is_event_chair(old.event_id) then
        if old.coordinator_id is distinct from auth.uid()
           or new.id is distinct from old.id
           or new.event_id is distinct from old.event_id
           or new.coordinator_id is distinct from old.coordinator_id
           or new.created_at is distinct from old.created_at then
            raise exception 'Coordinators may only edit their own division name';
        end if;
    end if;
    return new;
end;
$$;

create trigger divisions_guard_update
before update on public.divisions
for each row execute function public.guard_division_update();

create policy "admin or chair can delete divisions"
on public.divisions
for delete
to authenticated
using (
    public.is_admin()
    or public.is_event_chair(event_id)
);

