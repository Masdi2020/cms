-- ============================================================
-- 1. ENUM TYPES
-- ============================================================

create type public.user_role as enum (
    'admin',
    'user'
);

create type public.task_priority as enum (
    'low',
    'medium',
    'high'
);

create type public.task_status as enum (
    'todo',
    'in_progress',
    'done'
);

create type public.attachment_type as enum (
    'file',
    'link'
);

-- ============================================================
-- 2. USERS
-- Password dikelola oleh Supabase Auth.
-- ============================================================

create table public.users (
    id uuid primary key
        references auth.users(id)
        on delete cascade,
    name varchar(100) not null,
    email varchar(255) not null unique,
    phone varchar(30),
    role public.user_role not null default 'user',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    username text unique
);

-- ============================================================
-- 3. EVENTS
-- ============================================================

create table public.events (
    id bigint generated by default as identity primary key,
    title varchar(150) not null,
    description text,
    location varchar(255),
    start_date date not null,
    end_date date not null,
    ketua_panitia_id uuid
        references public.users(id)
        on update cascade
        on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint events_date_check
        check (end_date >= start_date)
);

-- ============================================================
-- 4. DIVISIONS
-- ============================================================

create table public.divisions (
    id bigint generated by default as identity primary key,
    event_id bigint not null
        references public.events(id)
        on update cascade
        on delete cascade,
    name varchar(100) not null,
    coordinator_id uuid references public.users(id) on update cascade on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint divisions_event_name_unique
        unique (event_id, name)
);

-- ============================================================
-- 5. MEMBERS
-- Relasi user dengan division.
-- Seorang user dapat mengikuti banyak event/divisi.
-- ============================================================

create table public.members (
    id bigint generated by default as identity primary key,
    user_id uuid not null
        references public.users(id)
        on update cascade
        on delete cascade,
    division_id bigint not null
        references public.divisions(id)
        on update cascade
        on delete cascade,
    created_at timestamptz not null default now(),
    constraint members_user_division_unique
        unique (user_id, division_id)
);

-- ============================================================
-- 6. TASKS
-- ============================================================

create table public.tasks (
    id bigint generated by default as identity primary key,
    division_id bigint not null
        references public.divisions(id)
        on update cascade
        on delete cascade,
    assigned_to uuid
        references public.users(id)
        on update cascade
        on delete set null,
    title varchar(150) not null,
    description text,
    deadline timestamptz,
    priority public.task_priority not null default 'medium',
    status public.task_status not null default 'todo',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- ============================================================
-- 7. ATTACHMENTS
-- MVP: satu task memiliki satu lampiran.
-- type = file -> file_name + file_path
-- type = link -> url
-- ============================================================

create table public.attachments (
    id bigint generated by default as identity primary key,
    task_id bigint not null
        references public.tasks(id)
        on update cascade
        on delete cascade,
    uploaded_by uuid
        references public.users(id)
        on update cascade
        on delete set null,
    type public.attachment_type not null,
    file_name varchar(255),
    file_path varchar(500),
    url text,
    created_at timestamptz not null default now(),
    constraint attachments_task_unique unique (task_id),
    constraint attachments_type_check
        check (
            (
                type = 'file'
                and file_name is not null
                and file_path is not null
                and url is null
            )
            or
            (
                type = 'link'
                and url is not null
                and file_path is null
            )
        )
);

-- ============================================================
-- 8. COMMENTS
-- ============================================================

create table public.comments (
    id bigint generated by default as identity primary key,
    task_id bigint not null
        references public.tasks(id)
        on update cascade
        on delete cascade,
    user_id uuid
        references public.users(id)
        on update cascade
        on delete set null,
    comment text not null,
    created_at timestamptz not null default now()
);

